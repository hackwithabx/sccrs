"use client";

import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

interface ReportItem {
  category: string;
  status: "pass" | "warning" | "fail";
  finding: string;
  recommendation: string;
}

interface ReportData {
  appName: string;
  appUrl: string;
  notes: string;
  score: number;
  passCount: number;
  warnCount: number;
  failCount: number;
  items: ReportItem[];
}

export function generateSecurityReportPDF(data: ReportData) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 20;
  let y = 20;

  // ---- Header with branding ----
  // Green header bar
  doc.setFillColor(16, 185, 129); // #10b981
  doc.rect(0, 0, pageWidth, 40, "F");

  // Company name
  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.setTextColor(255, 255, 255);
  doc.text("SecureCodeReviews", margin, 18);

  // Tagline
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text("Application Security Platform", margin, 26);

  // Website URL
  doc.setFontSize(9);
  doc.text("https://securecodereviews.com", margin, 34);

  // Contact email on right
  doc.text("support@securecodereviews.com", pageWidth - margin, 34, {
    align: "right",
  });

  y = 55;

  // ---- Report Title ----
  doc.setTextColor(30, 30, 30);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Security Assessment Report", margin, y);
  y += 10;

  // ---- Report Metadata ----
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(100, 100, 100);
  doc.text(`Application: ${data.appName}`, margin, y);
  y += 6;
  doc.text(`URL: ${data.appUrl || "N/A"}`, margin, y);
  y += 6;
  doc.text(`Date: ${new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" })}`, margin, y);
  y += 6;
  doc.text(`Generated by: SecureCodeReviews.com`, margin, y);
  y += 12;

  // ---- Divider ----
  doc.setDrawColor(16, 185, 129);
  doc.setLineWidth(0.5);
  doc.line(margin, y, pageWidth - margin, y);
  y += 12;

  // ---- Executive Summary ----
  doc.setTextColor(30, 30, 30);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text("Executive Summary", margin, y);
  y += 10;

  // Score circle
  const scoreColor =
    data.score >= 80
      ? [16, 185, 129]  // green
      : data.score >= 60
      ? [234, 179, 8]   // yellow
      : [239, 68, 68];  // red

  doc.setFillColor(scoreColor[0], scoreColor[1], scoreColor[2]);
  doc.circle(margin + 15, y + 8, 15, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(255, 255, 255);
  doc.text(String(data.score), margin + 15, y + 12, { align: "center" });

  // Score label
  doc.setTextColor(100, 100, 100);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text("Security Score", margin + 35, y + 4);

  // Summary stats
  doc.setTextColor(16, 185, 129);
  doc.text(`${data.passCount} Passed`, margin + 35, y + 11);
  doc.setTextColor(234, 179, 8);
  doc.text(`${data.warnCount} Warnings`, margin + 65, y + 11);
  doc.setTextColor(239, 68, 68);
  doc.text(`${data.failCount} Failed`, margin + 100, y + 11);

  y += 30;

  // ---- Risk Level ----
  const riskLevel = data.score >= 80 ? "Low Risk" : data.score >= 60 ? "Medium Risk" : "High Risk";
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(30, 30, 30);
  doc.text(`Overall Risk Level: `, margin, y);
  doc.setTextColor(scoreColor[0], scoreColor[1], scoreColor[2]);
  doc.text(riskLevel, margin + 45, y);
  y += 12;

  // ---- Detailed Findings Table ----
  doc.setTextColor(30, 30, 30);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text("Detailed Findings", margin, y);
  y += 8;

  const tableData = data.items.map((item) => [
    item.category,
    item.status.toUpperCase(),
    item.finding,
    item.recommendation,
  ]);

  autoTable(doc, {
    startY: y,
    head: [["Category", "Status", "Finding", "Recommendation"]],
    body: tableData,
    margin: { left: margin, right: margin },
    styles: {
      fontSize: 8,
      cellPadding: 4,
    },
    headStyles: {
      fillColor: [16, 185, 129],
      textColor: 255,
      fontStyle: "bold",
    },
    columnStyles: {
      0: { cellWidth: 30, fontStyle: "bold" },
      1: { cellWidth: 18, halign: "center" },
      2: { cellWidth: 60 },
      3: { cellWidth: 60 },
    },
    didParseCell: (hookData) => {
      if (hookData.section === "body" && hookData.column.index === 1) {
        const status = hookData.cell.raw as string;
        if (status === "PASS") {
          hookData.cell.styles.textColor = [16, 185, 129];
          hookData.cell.styles.fontStyle = "bold";
        } else if (status === "WARNING") {
          hookData.cell.styles.textColor = [234, 179, 8];
          hookData.cell.styles.fontStyle = "bold";
        } else if (status === "FAIL") {
          hookData.cell.styles.textColor = [239, 68, 68];
          hookData.cell.styles.fontStyle = "bold";
        }
      }
    },
  });

  // Get the Y position after the table
  const finalY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 15;

  // ---- Notes Section ----
  if (data.notes) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.setTextColor(30, 30, 30);
    doc.text("Additional Notes", margin, finalY);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(100, 100, 100);
    const noteLines = doc.splitTextToSize(data.notes, pageWidth - 2 * margin);
    doc.text(noteLines, margin, finalY + 8);
  }

  // ---- Footer on every page ----
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    const pageHeight = doc.internal.pageSize.getHeight();

    // Footer divider
    doc.setDrawColor(200, 200, 200);
    doc.setLineWidth(0.3);
    doc.line(margin, pageHeight - 20, pageWidth - margin, pageHeight - 20);

    // Footer text
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.text(
      "SecureCodeReviews.com — Application Security Platform",
      margin,
      pageHeight - 14
    );
    doc.text(
      `Page ${i} of ${pageCount}`,
      pageWidth - margin,
      pageHeight - 14,
      { align: "right" }
    );
    doc.text(
      "CONFIDENTIAL — This report is generated for the sole use of the intended recipient.",
      margin,
      pageHeight - 9
    );
  }

  // Save the PDF
  doc.save(`SCR-Security-Report-${data.appName.replace(/\s+/g, "-")}-${new Date().toISOString().split("T")[0]}.pdf`);
}
